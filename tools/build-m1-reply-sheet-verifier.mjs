// Build the self-contained verifier for the hosted parent's JavaScript runner.
// No filesystem, package, network or credential access is needed at runtime.
import { writeFile } from 'node:fs/promises';
import { REPLY_HEADERS, HEALTH_HEADERS, PROJECTION_LIMIT, verifyReplyProjection } from '../netlify/functions/_lib/m1-reply-projection.mjs';
function digestHash(value) {
  const input = typeof value === 'string' ? value : JSON.stringify(value), bytes = [];
  for (const character of input) {
    let c = character.codePointAt(0); if (c >= 0xd800 && c <= 0xdfff) c = 0xfffd;
    if (c < 128) bytes.push(c);
    else if (c < 2048) bytes.push(192 | c >>> 6, 128 | c & 63);
    else if (c < 65536) bytes.push(224 | c >>> 12, 128 | c >>> 6 & 63, 128 | c & 63);
    else bytes.push(240 | c >>> 18, 128 | c >>> 12 & 63, 128 | c >>> 6 & 63, 128 | c & 63);
  }
  const bits = bytes.length * 8, high = Math.floor(bits / 4294967296), low = bits >>> 0;
  bytes.push(128); while (bytes.length % 64 !== 56) bytes.push(0);
  for (const n of [high, low]) for (let s = 24; s >= 0; s -= 8) bytes.push(n >>> s & 255);
  const constants = [], state = [];
  for (let n = 2; constants.length < 64; n++) {
    let prime = true; for (let p = 2; p * p <= n; p++) if (n % p === 0) { prime = false; break; }
    if (!prime) continue;
    if (state.length < 8) state.push((Math.sqrt(n) % 1 * 4294967296) >>> 0);
    constants.push((Math.pow(n, 1 / 3) % 1 * 4294967296) >>> 0);
  }
  const rotate = (x, n) => x >>> n | x << (32 - n);
  for (let start = 0; start < bytes.length; start += 64) {
    const w = new Array(64);
    for (let i = 0; i < 16; i++) w[i] = bytes[start + i * 4] << 24 | bytes[start + i * 4 + 1] << 16 | bytes[start + i * 4 + 2] << 8 | bytes[start + i * 4 + 3];
    for (let i = 16; i < 64; i++) {
      const x = w[i - 15], y = w[i - 2];
      w[i] = ((rotate(x, 7) ^ rotate(x, 18) ^ x >>> 3) + w[i - 16] + (rotate(y, 17) ^ rotate(y, 19) ^ y >>> 10) + w[i - 7]) >>> 0;
    }
    let [a,b,c,d,e,f,g,h] = state;
    for (let i = 0; i < 64; i++) {
      const t1 = (h + (rotate(e, 6) ^ rotate(e, 11) ^ rotate(e, 25)) + (e & f ^ ~e & g) + constants[i] + w[i]) >>> 0;
      const t2 = ((rotate(a, 2) ^ rotate(a, 13) ^ rotate(a, 22)) + (a & b ^ a & c ^ b & c)) >>> 0;
      h = g; g = f; f = e; e = d + t1 >>> 0; d = c; c = b; b = a; a = t1 + t2 >>> 0;
    }
    [a,b,c,d,e,f,g,h].forEach((v, i) => { state[i] = state[i] + v >>> 0; });
  }
  return state.map(n => n.toString(16).padStart(8, '0')).join('');
}
const normalizedRows = (rows, width) => rows.map(r => Array.from({ length: width }, (_, i) => r[i] ?? ''));
const fail = code => { throw Object.assign(new Error(code), { code }); };
await writeFile(new URL('./m1-reply-sheet-portable.js', import.meta.url),
  '// Generated by build-m1-reply-sheet-verifier.mjs. Pinned, no I/O, no credentials.\n(() => {\n' +
  'const REPLY_HEADERS = ' + JSON.stringify(REPLY_HEADERS) + ';\nconst HEALTH_HEADERS = ' + JSON.stringify(HEALTH_HEADERS) + ';\nconst PROJECTION_LIMIT = ' + PROJECTION_LIMIT + ';\n' +
  digestHash.toString() + '\nconst normalizedRows = ' + normalizedRows.toString() + ';\nconst fail = ' + fail.toString() + ';\n' + verifyReplyProjection.toString() +
  '\nglobalThis.GibReplySheetVerifier = Object.freeze({ verify: verifyReplyProjection, hash: digestHash });\n})();\n');
